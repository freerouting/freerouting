  /** Serialize. */
  public byte[] serialize(boolean basicProfile) {
    try {
      ByteArrayOutputStream outputStream = new ByteArrayOutputStream();
      ObjectOutputStream objectStream = new ObjectOutputStream(outputStream);

      if (basicProfile) {
        objectStream.writeObject(this.getTraces());
        objectStream.writeObject(this.getVias());
        objectStream.writeObject(this.itemList);
      } else {
        objectStream.writeObject(this);
      }

      objectStream.close();

      return outputStream.toByteArray();
    } catch (Exception e) {
      FRLogger.error("Couldn't serialize board", e);
    }

    return null;
  }

  /** Clone. */
  @Override
  public BasicBoard clone() {
    return deserialize(this.serialize(false));
  }

  /** Returns an MD5 hash of the board trace state. */
  public String getHash() {
    try {
      MessageDigest digest = MessageDigest.getInstance("MD5");
      digest.update(this.serialize(true));
      byte[] hashedBytes = digest.digest();

      return convertByteArrayToHexString(hashedBytes);
    } catch (Exception e) {
      FRLogger.error("Couldn't calculate hash for board", e);
    }

    return null;
  }

  /** Returns the number of trace ID differences compared to another board. */
  public int diffTraces(BasicBoard compareTo) {
    int result = 0;
    HashSet<Integer> traceIds = new HashSet<>();
    for (Trace trace : this.getTraces()) {
      traceIds.add(trace.getIdNo());
    }

    for (Trace trace : compareTo.getTraces()) {
      if (!traceIds.contains(trace.getIdNo())) {
        result++;
      } else {
        traceIds.remove(trace.getIdNo());
      }
    }
    result += traceIds.size();

    return result;
  }

  /**
   * Inserts a trace into the board, whose geometry is described by a Polyline. p_clearance_class is
   * the index in the clearanceMatrix, which describes the required clearance restrictions to other
   * items. Because no internal cleaning of items is done, the new inserted item can be returned.
   */
  public PolylineTrace insertTraceWithoutCleaning(
      Polyline polyline,
      int layer,
      int halfWidth,
      int[] netNoArr,
      int clearanceClass,
      FixedState fixedState) {
    if (polyline.cornerCount() < 2) {
      return null;
    }
    PolylineTrace newTrace =
        new PolylineTrace(
            polyline, layer, halfWidth, netNoArr, clearanceClass, 0, 0, fixedState, this);
    if (newTrace.firstCorner().equals(newTrace.lastCorner())) {
      if (fixedState.ordinal() < FixedState.USER_FIXED.ordinal()) {
        return null;
      }
    }
    insertItem(newTrace);
    if (newTrace.netsNormal()) {
      maxTraceHalfWidth = Math.max(maxTraceHalfWidth, halfWidth);
      minTraceHalfWidth = Math.min(minTraceHalfWidth, halfWidth);
    }
    return newTrace;
  }

  /**
   * Inserts a trace into the board, whose geometry is described by a Polyline. p_clearance_class is
   * the index in the clearanceMatrix, which describes the required clearance restrictions to other
   * items.
   */
  public void insertTrace(
      Polyline polyline,
      int layer,
      int halfWidth,
      int[] netNoArr,
      int clearanceClass,
      FixedState fixedState) {
    PolylineTrace newTrace =
        insertTraceWithoutCleaning(
            polyline, layer, halfWidth, netNoArr, clearanceClass, fixedState);
    if (newTrace == null) {
      return;
    }
    IntOctagon clipShape = null;
    if (this instanceof RoutingBoard board) {
      ChangedArea changedArea = board.changedArea;
      if (changedArea != null) {
        clipShape = changedArea.getArea(layer);
      }
    }

    try {
      newTrace.normalize(clipShape);
    } catch (Exception e) {
      // Normalization can fail for geometrically degenerate trace segments (e.g. caused by
      // malformed input geometry or extreme routing situations). The segment is skipped and
      // the connection may remain unrouted. This is non-critical — other segments will continue.
      FRLogger.warn(
          "A trace segment could not be normalized and was skipped. "
              + "Affected net may have an unrouted connection. Cause: "
              + e.getMessage());
      FRLogger.debug("BasicBoard.insert_trace_segment: normalization exception detail: " + e);
    }
  }

  /**
   * Inserts a trace into the board, whose geometry is described by an array of points, and cleans
   * up the net.
   */
  public void insertTrace(
      Point[] points,
      int layer,
      int halfWidth,
      int[] netNoArr,
      int clearanceClass,
      FixedState fixedState) {
    for (int i = 0; i < points.length; i++) {
      if (!this.boundingBox.contains(points[i])) {
        FRLogger.warn("LayeredBoard.insert_trace: input point out of range");
      }
    }
    Polyline poly = new Polyline(points);
    insertTrace(poly, layer, halfWidth, netNoArr, clearanceClass, fixedState);
  }

  /**
   * Inserts a via into the board. p_attach_allowed indicates, if the via may overlap with smd pins
   * of the same net.
   */
  public Via insertVia(
      Padstack padstack,
      Point center,
      int[] netNoArr,
      int clearanceClass,
      FixedState fixedState,
      boolean attachAllowed) {
    Via newVia =
        new Via(
            padstack,
            center,
            netNoArr,
            clearanceClass,
            0,
            0,
            fixedState,
            attachAllowed,
            this);
    insertItem(newVia);
    int fromLayer = padstack.fromLayer();
    int toLayer = padstack.toLayer();
    for (int i = fromLayer; i < toLayer; i++) {
      for (int currNetNo : netNoArr) {
        splitTraces(center, i, currNetNo);
      }
    }
    return newVia;
  }

  /**
   * Inserts a special escape via into the board for the fanout escalation phase. An escape via sits
   * directly on top of an SMD pin to provide a layer transition to an inner routing layer. On the
   * SMD layer it uses SMD-to-SMD clearance rules (because its copper is inside the SMD pad
   * footprint); on inner layers it uses normal via clearance.
   *
   * @param padstack The padstack describing the via geometry
   * @param center The center point (at the SMD pin center)
   * @param netNoArr The net numbers
   * @param clearanceClass The clearance class to use
   * @param fixedState The fixed state
   * @param smdLayer The SMD layer where the pin lives (clearance exception layer)
   */
  public Via insertEscapeVia(
      Padstack padstack,
      Point center,
      int[] netNoArr,
      int clearanceClass,
      FixedState fixedState,
      int smdLayer) {
    Via newVia =
        new Via(padstack, center, netNoArr, clearanceClass, 0, 0, fixedState, true, this);
    newVia.isEscapeVia = true;
    newVia.escapeViaSmdLayer = smdLayer;
    insertItem(newVia);
    int fromLayer = padstack.fromLayer();
    int toLayer = padstack.toLayer();
    for (int i = fromLayer; i <= toLayer; i++) {
      for (int currNetNo : netNoArr) {
        splitTraces(center, i, currNetNo);
      }
    }
    return newVia;
  }


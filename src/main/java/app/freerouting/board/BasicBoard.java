  /** Normalizes the traces of this net. */
  public boolean normalizeTraces(int netNo) {
    if (normalizeSuppressedNetNos == null) {
      normalizeSuppressedNetNos = new HashSet<>();
    }
    if (normalizeSuppressedNetNos.contains(netNo)) {
      String netName =
          rules != null && rules.nets != null && rules.nets.get(netNo) != null
              ? rules.nets.get(netNo).name
              : String.valueOf(netNo);
      FRLogger.debug(
          "BasicBoard.normalize_traces: skipping net '"
              + netName
              + "' because normalization already hit the oscillation cap on this board candidate.");
      return false;
    }
    boolean result = false;
    boolean somethingChanged = true;
    int iterationCount = 0;
    while (somethingChanged) {
      if (++iterationCount > MAX_NORMALIZE_ITERATIONS) {
        // Safety valve: after this many passes the outer loop has not converged.
        // This can happen when a pair of traces keeps oscillating between a split state
        // and a re-combined state (e.g. a self-intersecting or zero-length segment that
        // the geometry engine cannot cleanly normalise).  Stop here rather than hanging
        // the board-load thread for minutes.
        String netName =
            rules != null && rules.nets != null && rules.nets.get(netNo) != null
                ? rules.nets.get(netNo).name
                : String.valueOf(netNo);
        FRLogger.warn(
            "BasicBoard.normalize_traces: reached "
                + MAX_NORMALIZE_ITERATIONS
                + " iterations for net '"
                + netName
                + "' — stopping to prevent hang."
                + " The board geometry for this net may be oscillating (split/combine cycle);"
                + " traces are kept as-is and further normalization for this net is suppressed"
                + " on this board candidate.");
        normalizeSuppressedNetNos.add(netNo);
        break;
      }
      somethingChanged = false;

      // Collect traces for this net on this iteration to avoid ConcurrentModificationException
      // on the board's itemList during iteration, and to avoid scanning the entire board
      // repeatedly.
      java.util.List<PolylineTrace> netTraces = new java.util.ArrayList<>();
      Iterator<UndoableObjects.UndoableObjectNode> it = itemList.startReadObject();
      for (; ; ) {
        Item currItem;
        try {
          currItem = (Item) itemList.readObject(it);
        } catch (ConcurrentModificationException _) {
          // If the board's item list was modified during collection (should be rare during
          // collection itself),
          // set somethingChanged to true to retry from a fresh state.
          somethingChanged = true;
          break;
        }
        if (currItem == null) {
          break;
        }
        if (currItem.containsNet(netNo)
            && currItem instanceof PolylineTrace currTrace
            && currItem.isOnTheBoard()) {
          netTraces.add(currTrace);
        }
      }

      if (somethingChanged) {
        continue;
      }

      for (PolylineTrace currTrace : netTraces) {
        if (currTrace.isOnTheBoard()) {
          if (currTrace.normalize(null)) {
            somethingChanged = true;
            result = true;
          } else if (!currTrace.isUserFixed() && this.removeIfCycle(currTrace)) {
            somethingChanged = true;
            result = true;
          }
        }
      }
    }
    return result;
  }

  /** Normalizes the traces of all nets on the board in a single optimized pass. */
  public boolean normalizeAllTraces() {
    boolean result = false;
    // Group all PolylineTrace items by net
    java.util.Map<Integer, java.util.List<PolylineTrace>> tracesByNet = new java.util.HashMap<>();
    Iterator<UndoableObjects.UndoableObjectNode> it = itemList.startReadObject();
    for (; ; ) {
      Item currItem;
      try {
        currItem = (Item) itemList.readObject(it);
      } catch (java.util.ConcurrentModificationException _) {
        // Retry collection if modified
        tracesByNet.clear();
        it = itemList.startReadObject();
        continue;
      }
      if (currItem == null) {
        break;
      }
      if (currItem instanceof PolylineTrace currTrace && currItem.isOnTheBoard()) {
        for (int netNo : currTrace.netNoArr) {
          tracesByNet.computeIfAbsent(netNo, k -> new java.util.ArrayList<>()).add(currTrace);
        }
      }
    }

    for (java.util.Map.Entry<Integer, java.util.List<PolylineTrace>> entry :
        tracesByNet.entrySet()) {
      int netNo = entry.getKey();
      java.util.List<PolylineTrace> netTraces = entry.getValue();
      boolean somethingChanged = true;
      int iterationCount = 0;
      while (somethingChanged) {
        if (++iterationCount > MAX_NORMALIZE_ITERATIONS) {
          String netName =
              rules != null && rules.nets != null && rules.nets.get(netNo) != null
                  ? rules.nets.get(netNo).name
                  : String.valueOf(netNo);
          FRLogger.warn(
              "BasicBoard.normalize_all_traces: reached "
                  + MAX_NORMALIZE_ITERATIONS
                  + " iterations for net '"
                  + netName
                  + "' — stopping to prevent hang.");
          break;
        }
        somethingChanged = false;

        for (PolylineTrace currTrace : netTraces) {
          if (currTrace.isOnTheBoard()) {
            if (currTrace.normalize(null)) {
              somethingChanged = true;
              result = true;
            } else if (!currTrace.isUserFixed() && this.removeIfCycle(currTrace)) {
              somethingChanged = true;
              result = true;
            }
          }
        }

        // If something changed, collect the traces for this net again
        if (somethingChanged) {
          netTraces.clear();
          Iterator<UndoableObjects.UndoableObjectNode> it2 = itemList.startReadObject();
          for (; ; ) {
            Item currItem;
            try {
              currItem = (Item) itemList.readObject(it2);
            } catch (java.util.ConcurrentModificationException _) {
              netTraces.clear();
              it2 = itemList.startReadObject();
              continue;
            }
            if (currItem == null) {
              break;
            }
            if (currItem.containsNet(netNo)
                && currItem instanceof PolylineTrace currTrace
                && currItem.isOnTheBoard()) {
              netTraces.add(currTrace);
            }
          }
        }
      }
    }
    return result;
  }

  /**
   * Looks for traces of the input net on the input layer, so that p_location is on the trace
   * polygon, and splits these traces. Returns false, if no trace was split.
   */
  public boolean splitTraces(Point location, int layer, int netNo) {
    ItemSelectionFilter filter =
        new ItemSelectionFilter(ItemSelectionFilter.SelectableChoices.TRACES);
    Collection<Item> pickedItems = this.pickItems(location, layer, filter);
    IntOctagon locationShape = TileShape.getInstance(location).boundingOctagon();
    boolean traceSplit = false;
    for (Item currItem : pickedItems) {
      Trace currTrace = (Trace) currItem;
      if (currTrace.containsNet(netNo)) {
        Collection<PolylineTrace> splitPieces = currTrace.split(locationShape);
        if (splitPieces.size() != 1) {
          traceSplit = true;
        }
      }
    }
    return traceSplit;
  }

  /** Returns a Collection of Collections of items forming a connected set. */
  public Collection<Collection<Item>> getConnectedSets(int netNo) {
    Collection<Collection<Item>> result = new LinkedList<>();
    if (netNo <= 0) {
      return result;
    }
    SortedSet<Item> itemsToHandle = new TreeSet<>();
    Iterator<UndoableObjects.UndoableObjectNode> it = this.itemList.startReadObject();
    for (; ; ) {
      Item currItem = (Item) itemList.readObject(it);
      if (currItem == null) {
        break;
      }
      if (currItem instanceof Connectable && currItem.containsNet(netNo)) {
        itemsToHandle.add(currItem);
      }
    }
    Iterator<Item> it2 = itemsToHandle.iterator();
    while (it2.hasNext()) {
      Item currItem = it2.next();
      Collection<Item> nextConnectedSet = currItem.getConnectedSet(netNo);
      result.add(nextConnectedSet);
      itemsToHandle.removeAll(nextConnectedSet);
      it2 = itemsToHandle.iterator();
    }
    return result;
  }


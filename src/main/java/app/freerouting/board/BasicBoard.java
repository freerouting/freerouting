  /**
   * Creates a new instance of a routing Board with surrounding box p_bounding_box Rules contains
   * the restrictions to obey when inserting items. Among other things it may contain a clearance
   * matrix. p_observers is used for synchronisation, if the board is generated by a host database,
   * otherwise it is null. If p_test_level != RELEASE_VERSION, some features may be used, which are
   * still in experimental state. Warnings for debugging may be printed depending on the size of
   * p_test_level.
   */
  public BasicBoard(
      IntBox boundingBox,
      LayerStructure layerStructure,
      PolylineShape[] outlineShapes,
      int outlineClClassNo,
      BoardRules rules,
      Communication communication) {
    this.layerStructure = layerStructure;
    this.rules = rules;
    library = new BoardLibrary();
    itemList = new UndoableObjects();
    components = new Components();
    this.communication = communication;
    this.boundingBox = boundingBox;
    searchTreeManager = new SearchTreeManager(this);
    rules.nets.setBoard(this);
    insertOutline(outlineShapes, outlineClClassNo);
  }

  /** Deserialize. */
  public static BasicBoard deserialize(byte[] objectByteArray) {
    try {
      ByteArrayInputStream inputStream = new ByteArrayInputStream(objectByteArray);
      ObjectInputStream objectStream = new ObjectInputStream(inputStream);

      return (BasicBoard) objectStream.readObject();
    } catch (Exception e) {
      FRLogger.error("Couldn't deserialize board", e);
    }

    return null;
  }

  private static String convertByteArrayToHexString(byte[] arrayBytes) {
    StringBuilder stringBuffer = new StringBuilder();
    for (int i = 0; i < arrayBytes.length; i++) {
      stringBuffer.append(Integer.toString((arrayBytes[i] & 0xff) + 0x100, 16).substring(1));
    }
    return stringBuffer.toString();
  }

  private static boolean isItemActivityDebugCandidate(Item item) {
    IntBox bounds = item.boundingBox();
    IntBox debugWindow = new IntBox(1620000, -1105000, 1930000, -1003000);
    return bounds != null && bounds.intersects(debugWindow);
  }

  private static String firstNetOrNone(Item item) {
    return item.netCount() > 0 ? Integer.toString(item.getNetNo(0)) : "none";
  }

  private static String describeBounds(IntBox bounds) {
    if (bounds == null) {
      return "null";
    }
    return "[("
        + bounds.ll.x
        + ","
        + bounds.ll.y
        + ")..("
        + bounds.ur.x
        + ","
        + bounds.ur.y
        + ")]";
  }

